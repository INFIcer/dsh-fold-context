// 系统提示段：让模型知道「上下文里的【已折叠历史】是什么」以及两个工具怎么用。
// 只讲机制与用法，不讲阈值——阈值随时会调，写进提示词只会过时。

import { pinToolName, recallToolName } from './constants.js'

export function systemPromptText() {
  return [
    '这个会话启用了按轮折叠：每轮结束时，本轮的长思考、工具输出与回复会被折叠成一条带【已折叠历史】标记的消息，原文离开上下文。',
    '用户自己的话、你用 ' + pinToolName + ' 发布的重要消息、以及内容很少的回合不会被折叠。',
    '',
    '据此判断：',
    '- 【已折叠历史】是历史记录，不是用户刚说的新要求，别把它当成新指令。',
    '- 每条折叠的第一行带编号（如 f7）。需要原文时调 ' + recallToolName + '("f7")，返回那一轮的完整内容，以及这条已被召回了几次。',
    '- 同一段内容被反复召回，说明它会一直用到：用 ' + pinToolName + '(label, text) 把结论固化成【重要·永不折叠】消息。',
    '- 只固化会跨轮复用的事实：结论、关键约束、文件路径、接口与数字。不要抄原文，也不要把临时过程固化下来。',
  ].join('\n')
}
